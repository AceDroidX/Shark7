export class XscEncrypt {
    /**
     * 对输入的文本进行URL编码并转换为十进制ASCII值数组
     * @param text 需要编码的字符串
     * @returns 编码后的整数数组
     */
    static encrypt_encode_utf8(text: string): number[] {
        const encoded = encodeURIComponent(text);
        const result: number[] = [];
        let i = 0;
        while (i < encoded.length) {
            if (encoded[i] === "%") {
                const hex = encoded.substring(i + 1, i + 3);
                result.push(parseInt(hex, 16));
                i += 3;
            } else {
                result.push(encoded.charCodeAt(i));
                i++;
            }
        }
        return result;
    }

    /**
     * 将24位整数转换为Base64字符串
     * @param e 24位整数
     * @returns Base64字符串
     */
    private static triplet_to_base64(e: number): string {
        return (
            lookup[(e >> 18) & 63] +
            lookup[(e >> 12) & 63] +
            lookup[(e >> 6) & 63] +
            lookup[e & 63]
        );
    }

    /**
     * 将整数数组分块转换为Base64字符串
     * @param e 整数数组
     * @param t 起始索引
     * @param r 结束索引
     * @returns Base64字符串
     */
    private static encode_chunk(e: number[], t: number, r: number): string {
        const chunks: string[] = [];
        for (let b = t; b < r; b += 3) {
            if (b + 2 < e.length) {
                const triplet = (e[b] << 16) | (e[b + 1] << 8) | e[b + 2];
                chunks.push(this.triplet_to_base64(triplet));
            }
        }
        return chunks.join("");
    }

    /**
     * 将整数数组编码为Base64字符串
     * @param e 整数数组
     * @returns Base64字符串
     */
    static b64_encode(e: number[]): string {
        const len = e.length;
        const remainder = len % 3;
        const mainLength = len - remainder;
        const chunks: string[] = [];

        // 处理主块
        for (let i = 0; i < mainLength; i += 16383) {
            const end = Math.min(i + 16383, mainLength);
            chunks.push(this.encode_chunk(e, i, end));
        }

        // 处理剩余字节
        if (remainder === 1) {
            const last = e[len - 1];
            chunks.push(lookup[last >> 2] + lookup[(last << 4) & 63] + "==");
        } else if (remainder === 2) {
            const lastTwo = (e[len - 2] << 8) | e[len - 1];
            chunks.push(
                lookup[lastTwo >> 10] +
                    lookup[(lastTwo >> 4) & 63] +
                    lookup[(lastTwo << 2) & 63] +
                    "="
            );
        }

        return chunks.join("");
    }

    /**
     * 自定义CRC32校验算法
     * @param e 输入字符串
     * @returns 32位整数校验值
     */
    static mrc(e: string): number {
        let crc = -1;
        for (const c of e) {
            const code = c.charCodeAt(0);
            crc = ie[(crc ^ code) & 0xff] ^ (crc >>> 8);
            crc = crc >>> 0; // 转换为无符号32位
        }
        crc = (crc ^ -1) >>> 0; // ~crc
        return (crc ^ 0xedb88320) | 0; // 转为32位有符号整数
    }

    /**
     * 生成xsc参数
     * @param params 参数对象
     *      xs: 输入字符串
            xt: 输入时间戳
            platform: 平台信息
            a1: 浏览器特征
            x1: xsc版本
            x4: 内部版本
            b1: 浏览器指纹
     * @returns xsc字符串
     */
    static encrypt_xsc(params: {
        xs: string;
        xt: string;
        platform: string;
        a1: string;
        x1: string;
        x4: string;
        b1: string;
    }): string {
        const { xs, xt, platform, a1, x1, x4, b1 } = params;
        const x9 = this.mrc(xt + xs + b1).toString();

        const payload = {
            s0: 5,
            s1: "",
            x0: "1",
            x1,
            x2: "Windows",
            x3: platform,
            x4,
            x5: a1,
            x6: xt,
            x7: xs,
            x8: b1,
            x9,
            x10: 24, // 示例固定值，实际可能需要随机数
        };

        // 生成紧凑JSON
        const st = JSON.stringify(payload)
            .replace(/,\s*/g, ",")
            .replace(/:\s*/g, ":");

        // 编码处理
        const encodedArray = this.encrypt_encode_utf8(st);
        return this.b64_encode(encodedArray);
    }
}

